from io import BytesIO

from celery import shared_task
from django.core.files.base import ContentFile
from django.utils import timezone
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

from apps.billing.models import Invoice


def _money(cents: int, currency: str) -> str:
    return f"{currency} {cents / 100:,.2f}"


@shared_task(bind=True, autoretry_for=(Exception,), retry_backoff=True, max_retries=3)
def generate_invoice_pdf(self, invoice_id: int) -> None:
    invoice = (
        Invoice.objects.select_related("tenant", "subscription")
        .prefetch_related("lines")
        .get(pk=invoice_id)
    )
    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4, title=f"Invoice {invoice.number or invoice.pk}")
    width, height = A4
    y = height - 56
    pdf.setFont("Helvetica-Bold", 20)
    pdf.drawString(48, y, "TenantBill Invoice")
    y -= 30
    pdf.setFont("Helvetica", 10)
    details = (
        f"Invoice: {invoice.number or invoice.external_invoice_id}",
        f"Tenant: {invoice.tenant.name}",
        f"Customer: {invoice.subscription.customer_name}",
        f"Status: {invoice.get_status_display()}",
    )
    for detail in details:
        pdf.drawString(48, y, detail)
        y -= 16
    y -= 12
    pdf.setFont("Helvetica-Bold", 10)
    pdf.drawString(48, y, "Description")
    pdf.drawRightString(width - 48, y, "Amount")
    y -= 18
    pdf.setFont("Helvetica", 9)
    for line in invoice.lines.all():
        if y < 72:
            pdf.showPage()
            y = height - 56
            pdf.setFont("Helvetica", 9)
        pdf.drawString(48, y, (line.description or line.external_line_id)[:75])
        pdf.drawRightString(width - 48, y, _money(line.amount_cents, line.currency))
        y -= 16
    y -= 10
    pdf.setFont("Helvetica-Bold", 11)
    pdf.drawRightString(width - 48, y, f"Total: {_money(invoice.total_cents, invoice.currency)}")
    pdf.setFont("Helvetica", 8)
    pdf.drawString(48, 36, "Generated by TenantBill")
    pdf.save()

    filename = f"invoice-{invoice.external_invoice_id}.pdf"
    invoice.pdf.save(filename, ContentFile(buffer.getvalue()), save=False)
    invoice.pdf_generated_at = timezone.now()
    invoice.save(update_fields=("pdf", "pdf_generated_at", "updated_at"))
